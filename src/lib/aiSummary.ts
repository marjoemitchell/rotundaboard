import type { AiSummary } from '../types'
import { formatDate } from './format'

// The note under an AI bill summary: what the summary was made from. An LC
// draft has a requester, not a sponsor.
export function aiSummaryNote(summary: AiSummary, isDraft: boolean): string {
  if (summary.source === 'text' && summary.versionLabel) {
    const when = summary.versionPostedAt ? ` (${formatDate(summary.versionPostedAt)})` : ''
    return `Generated by AI from the bill text, ${summary.versionLabel}${when}. It may be incomplete or wrong. Verify it against the official bill record.`
  }
  const person = isDraft ? 'requester' : 'sponsor'
  return `Generated by AI from the bill title, subject, ${person}, and status, not from the bill text. It may be incomplete or wrong. Verify it against the official bill record.`
}
